/// Builds [TpFileSelectionDeps] with huji platform adapters and l10n strings.
TpFileSelectionDeps hujiFileSelectionDeps(BuildContext context) {
  return TpFileSelectionDeps(
    filesystem: IoFilesystemPort(),
    permission: PermissionHandlerPort(),
    gallery: PlatformCapability.supportsGalleryAccess
        ? PhotoManagerGalleryPort()
        : null,
    desktop: PlatformCapability.isDesktop ? DesktopFilePickerPort() : null,
    preview: VideoPlayerPreviewPort(),
    strings: tpFileSelectionStringsFromL10n(context.hujiL10n),
    isDesktop: () => PlatformCapability.isDesktop,
  );
}

